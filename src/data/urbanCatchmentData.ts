// Generate realistic 20x20 DEM Micro-Topography Grid
export function generateDemoDEMGrid(): DEMCell[] {
  const cells: DEMCell[] = [];
  const rows = 20;
  const cols = 20;
  const latStep = (DEMO_ZONE_BOUNDS.maxLat - DEMO_ZONE_BOUNDS.minLat) / rows;
  const lngStep = (DEMO_ZONE_BOUNDS.maxLng - DEMO_ZONE_BOUNDS.minLng) / cols;

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const lat = DEMO_ZONE_BOUNDS.minLat + (r + 0.5) * latStep;
      const lng = DEMO_ZONE_BOUNDS.minLng + (c + 0.5) * lngStep;
      
      // Normalized coords (0 to 1)
      const u = c / (cols - 1); // West (0) to East (1)
      const v = r / (rows - 1); // South (0) to North (1)

      // Base topographic gradient: High at West/North-West (226m) sloping toward East/South-East (200m)
      let elev = 226 - (u * 22.0) - ((1 - v) * 5.0);

      // Add prominent depression / bowl sink at central-east basin (u~0.6, v~0.4)
      const distToBasinCenter = Math.hypot(u - 0.58, v - 0.42);
      if (distToBasinCenter < 0.35) {
        const depressionDepth = Math.cos((distToBasinCenter / 0.35) * (Math.PI / 2)) * 6.5;
        elev -= depressionDepth;
      }

      // Add underpass depression at (u~0.8, v~0.45)
      const distToUnderpass = Math.hypot(u - 0.78, v - 0.45);
      if (distToUnderpass < 0.2) {
        const underpassDepth = Math.cos((distToUnderpass / 0.2) * (Math.PI / 2)) * 5.0;
        elev -= underpassDepth;
      }

      // Determine Land Use
      let landUse: DEMCell['landUse'] = 'RESIDENTIAL_PAVED';
      let runoffC = 0.75;

      if (v > 0.8 && u < 0.4) {
        landUse = 'GREEN_PERMEABLE';
        runoffC = 0.25;
      } else if (Math.abs(v - 0.5) < 0.15 && Math.abs(u - 0.5) < 0.2) {
        landUse = 'COMMERCIAL_CONCRETE';
        runoffC = 0.92;
      } else if (u > 0.85 && v < 0.2) {
        landUse = 'WATER_BODY';
        runoffC = 0.10;
      }

      cells.push({
        id: `CELL_${r}_${c}`,
        gridX: c,
        gridY: r,
        lat,
        lng,
        elevationM: Math.round(elev * 10) / 10,
        slopePercent: Math.max(0.2, Math.round((2.5 - u * 1.5 + Math.random() * 0.4) * 10) / 10),
        aspectDeg: 135, // Sloping generally South-East
        landUse,
        runoffCoefficient: runoffC,
        catchmentAreaM2: Math.round((latStep * 111000) * (lngStep * 111000 * Math.cos((lat * Math.PI) / 180))),
        accumulatedWaterDepthCm: 0,
        surfaceWaterVolumeM3: 0,
      });
    }
  }

  return cells;
}
